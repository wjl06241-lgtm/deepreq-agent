    + '    }).join("");'
    + '    box.innerHTML=items||"<div style=padding:12px class=muted>无记录</div>"'
    + '  }).catch(function(e){box.innerHTML="<div style=padding:12px>"+esc("加载失败："+e.message)+"</div>"})'
    + '}'
    + 'function render(s){'
    + '  document.getElementById("updated").textContent="更新于 "+fmt(s.now);'
    + '  document.getElementById("cards").innerHTML='
    + '    card(s.today.userMessages,"今日用户消息")'
    + '    +card(s.today.answered,"今日已回答","#16a34a")'
    + '    +card(s.today.unanswered,"今日未回答",s.today.unanswered>0?"#dc2626":"inherit")'
