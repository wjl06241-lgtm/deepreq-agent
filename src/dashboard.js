    + '    +card(s.open.length,"待处理问题",s.open.length>0?"#dc2626":"inherit");'
    + '  renderOpen(s.open,s.timeoutSec);'
    + '  renderProjects(s.perProject);'
    + '  renderDays(s.days);'
    + '}'
    + 'function load(){api("/api/status").then(render).catch(function(e){document.getElementById("updated").textContent="加载失败："+e.message})}'
    + 'function loadChats(){api("/api/chats").then(function(d){renderChats(d.chats)})}'
    + 'document.getElementById("refresh").onclick=function(){load();loadChats()}'
    + 'load();loadChats();setInterval(function(){load();loadChats()},30000);'
    + '</scr' + 'ipt>'
  return head + script + '</body></html>'
