  const head = '<!doctype html><html lang="zh-CN"><head><meta charset="utf-8">'
    + '<meta name="viewport" content="width=device-width,initial-scale=1">'
    + '<title>需求助手 · 运营看板</title><style>'
    + 'body{font-family:system-ui,"Segoe UI","PingFang SC",sans-serif;margin:0;background:#f5f6f8;color:#1f2329}'
    + 'header{background:#fff;border-bottom:1px solid #e5e7eb;padding:12px 20px;display:flex;align-items:center;justify-content:space-between}'
