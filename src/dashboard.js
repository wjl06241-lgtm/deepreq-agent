    + '.msg.u{background:#f7faff}.msg.a{background:#f9fafb}'
    + '.msg .meta{color:#9aa1ab;font-size:11px;margin-bottom:2px}'
    + '</style></head><body>'
    + '<header><h1>需求助手 · 运营看板</h1><div><span id="updated" class="muted"></span> <button id="refresh">刷新</button></div></header>'
    + '<div class="cards" id="cards"></div>'
    + '<section><h2>未回答的问题</h2><table><thead><tr><th>时间</th><th>项目</th><th>用户</th><th>问题</th><th>已等待</th><th>状态</th><th></th></tr></thead><tbody id="openRows"></tbody></table></section>'
    + '<section><h2>今日各项目回答情况</h2><table><thead><tr><th>项目</th><th>用户消息</th><th>已回答</th><th>未回答</th><th>异常</th><th>回答率</th></tr></thead><tbody id="projRows"></tbody></table></section>'
