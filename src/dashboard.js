    + 'function api(path,opts){opts=opts||{};var sep=path.indexOf("?")>=0?"&":"?";var url=TOKEN?path+sep+"token="+encodeURIComponent(TOKEN):path;return fetch(url,opts).then(function(r){if(!r.ok)throw new Error("HTTP "+r.status);return r.json()})}'
