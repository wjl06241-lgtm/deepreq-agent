    + '      +"<td><button data-qid=\""+esc(q.qid)+"\" class=resolve>标记已处理</button></td></tr>"'
    + '  }).join("");'
    + '  rows.querySelectorAll("button.resolve").forEach(function(b){b.onclick=function(){'
    + '    api("/api/resolve",{method:"POST",headers:{"content-type":"application/json"},body:JSON.stringify({qid:b.dataset.qid})}).then(load).catch(function(e){alert(e.message)})'
    + '  }})'
    + '}'
    + 'function renderProjects(items){'
    + '  var rows=document.getElementById("projRows");'
    + '  if(!items.length){rows.innerHTML="<tr><td colspan=6 class=muted>暂无数据</td></tr>";return}'
