    + 'th,td{padding:8px 12px;text-align:left;border-bottom:1px solid #eef0f2}'
    + 'th{background:#fafbfc;color:#4b5563;font-weight:600}'
    + 'tr:last-child td{border-bottom:none}'
    + 'tr.clickable{cursor:pointer}'
    + 'tr.clickable:hover{background:#f7faff}'
    + '.muted{color:#9aa1ab;font-size:12px}'
    + '.badge{display:inline-block;padding:1px 8px;border-radius:99px;font-size:12px}'
    + '.badge.open{background:#fef2f2;color:#dc2626}'
