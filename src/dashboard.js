    + '    var rate=p.rate==null?"-":p.rate+"%";'
    + '    var color=p.unanswered>0?"#dc2626":"inherit";'
    + '    return "<tr><td>"+esc(p.projectName)+"</td><td>"+p.userMessages+"</td><td>"+p.answered+"</td><td style=color:"+color+">"+p.unanswered+"</td><td>"+p.errors+"</td><td>"+rate+"</td></tr>"'
    + '  }).join("")'
    + '}'
    + 'function renderDays(days){'
    + '  document.getElementById("dayRows").innerHTML=days.map(function(d){'
    + '    var rate=d.rate==null?"-":d.rate+"%";'
    + '    return "<tr><td>"+esc(d.day)+"</td><td>"+d.userMessages+"</td><td>"+d.answered+"</td><td>"+d.unanswered+"</td><td>"+d.errors+"</td><td>"+rate+"</td></tr>"'
    + '  }).join("")'
    + '}'
    + 'function renderChats(chats){'
    + '  var rows=document.getElementById("chatRows");'
    + '  if(!chats.length){rows.innerHTML="<tr><td colspan=6 class=muted>暂无会话</td></tr>";return}'
    + '  rows.innerHTML=chats.map(function(c){'
    + '    return "<tr class=clickable data-chat=\""+esc(c.chatId)+"\"><td>"+esc(c.platform+" / "+c.chatId)+"</td><td>"+esc(c.projectName||"默认会话")+"</td><td>"+esc(c.userName||"-")+"</td>"'
    + '      +"<td>"+esc(fmt(c.lastTs))+"</td><td>"+c.userCount+" / "+c.assistantCount+"</td><td class=snippet>"+esc(c.lastText)+"</td></tr>"'
    + '  }).join("");'
    + '  rows.querySelectorAll("tr.clickable").forEach(function(tr){tr.onclick=function(){loadRecords(tr.dataset.chat)}})'
    + '}'
    + 'function loadRecords(chatId){'
    + '  var box=document.getElementById("records");'
    + '  box.innerHTML="<div style=padding:12px class=muted>加载中…</div>";'
    + '  api("/api/records?chatId="+encodeURIComponent(chatId)+"&limit=200").then(function(d){'
    + '    var items=d.records.map(function(r){'
    + '      var cls=r.kind==="user_message"?"u":"a";'
    + '      var label=r.kind==="user_message"?"用户":(r.kind==="assistant_message"?"助手":(r.kind==="error"?"错误":r.kind));'
