  await assert.rejects(configs.upload(p1,'错误替换.md',Buffer.from('错误'),shared.id,'test'),e=>e.status===404)
  const ordinaryTools=await lib.tools('ordinary',null,'task-global',{projectFiles:()=>configs.entries(null)})
