  const p1=(await service.mutate('project',{enterpriseId:e1,name:'同名项目'},'test')).id
  await service.mutate('project',{enterpriseId:e2,name:'同名项目'},'test')
  await service.mutate('members',{id:p1,userIds:[uid1]},'test')
  await assert.rejects(service.mutate('members',{id:p1,userIds:[uid2]},'test'),/本企业/)
