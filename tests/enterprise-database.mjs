  await service.mutate('project',{id:p1,enterpriseId:e1,name:'同名项目',archived:true,prompt:'专属提示词'},'test');assert.equal((await service.catalog()).projects.find(p=>p.id===p1).archived,true)
  const root=await mkdtemp(join(tmpdir(),'project-config-')),configs=new ProjectConfiguration(pool,root)
  const initial=await configs.project(p1)
  const globalInitial=await configs.global();assert.equal(globalInitial.prompt,'')
  await configs.saveGlobal({prompt:'统一顶层测试规则',version:globalInitial.version},'test')
  await assert.rejects(configs.saveGlobal({prompt:'过期更新',version:globalInitial.version},'test'),e=>e.status===409)
  await assert.rejects(configs.saveGlobal({prompt:'a'.repeat(30001),version:1},'test'),e=>e.status===400)
  const anotherInstance=new ProjectConfiguration(pool,root)
  assert.equal((await anotherInstance.global()).prompt,'统一顶层测试规则')
  for(const project of [null,{name:'其他项目',prompt:'项目工作规则',explicitPrompt:true,soul:'项目人格',boundaries:'项目边界'}]){
    const combined=await buildSystemPrompt({root,assistantConfig:{systemPrompt:'默认'},project,globalPrompt:(await anotherInstance.global()).prompt,includeGlobalContext:false})
    assert(combined.startsWith('## 全局助手顶层规则'))
    assert(combined.includes('统一顶层测试规则'))
    if(project)assert(combined.includes('项目工作规则'))
  }
  await configs.saveGlobal({prompt:'',version:1},'test');assert.equal((await configs.global()).prompt,'')
  assert.equal((await db.query(`SELECT count(*)::int AS n FROM ${schema}.enterprise_audit WHERE action='global-config'`)).rows[0].n,2)
  console.log('GLOBAL-CONFIG-OK: shared storage, project and ordinary injection, conflict, validation, audit, clear')
