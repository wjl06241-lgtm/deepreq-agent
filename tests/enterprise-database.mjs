  await db.query((await readFile('docs/db/postgresql-v8.sql','utf8')).replaceAll('requirement_assistant',schema))
  await db.query((await readFile('docs/db/postgresql-v9.sql','utf8')).replaceAll('requirement_assistant',schema))
