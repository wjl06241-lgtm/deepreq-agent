  assert(globalContext.includes('全局参考摘要'));assert(globalContext.includes('不是顶层提示词'))
  assert(!globalContext.includes('严谨与坦诚'))
  console.log('GLOBAL-MATERIALS-OK: upload, ordinary/project read, project isolation, replacement, live revocation, original bytes preserved, no prompt promotion')
  console.log('PROJECT-CONFIG-OK: Soul, boundaries, prompt preservation, conflict detection, upload, read, replacement, disabled-file revocation, project isolation')
  console.log('ENTERPRISE-DATABASE-OK: CRUD, same-name projects, cross-enterprise rejection, rollback, member removal, archive')
