  assert(JSON.stringify(await tools.call('materials_read',{id:first.id})).includes('仅此项目'))
  const other=(await service.catalog()).projects.find(p=>p.enterpriseId===e2)
  const otherTools=await lib.tools('other',null,'other-task',{projectFiles:()=>configs.entries(other.id)})
  await assert.rejects(otherTools.call('materials_read',{id:first.id}),/不属于/)
  await assert.rejects(configs.toggle(other.id,first.id,false,'test'),/不属于/)
  const second=await configs.upload(p1,'背景.txt',Buffer.from('第二版背景'),first.id,'test')
  assert.equal((await configs.list(p1)).length,2)
  await assert.rejects(tools.call('materials_read',{id:first.id}),/不属于/)
  assert(JSON.stringify(await tools.call('materials_read',{id:second.id})).includes('第二版'))
