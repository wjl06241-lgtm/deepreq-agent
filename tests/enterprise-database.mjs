  await service.refresh(reg);assert.equal(reg.catalog[p1].soul,'严谨与坦诚')
  const prompt=await buildSystemPrompt({root,assistantConfig:{systemPrompt:'默认'},project:reg.catalog[p1],indexOnly:true,includeGlobalContext:false})
  assert(prompt.includes('严谨与坦诚'));assert(prompt.includes('未确认不得定稿'));assert(prompt.includes('背景事实'))
  const ordinary=await buildSystemPrompt({root,assistantConfig:{systemPrompt:'默认'},project:null,includeGlobalContext:false})
  assert(!ordinary.includes('严谨与坦诚'))
